// The one generation of src/schema.d.ts — the platform API's types — from the
// committed OpenAPI document (schemas/openapi/openapi.json) with
// openapi-typescript. scripts/gen.mjs writes or checks the file with it, and
// test/drift.test.ts compares it with the committed file, so the command, the
// CI step and the test can never disagree about the output.
import openapiTS, { astToString } from 'openapi-typescript';

export const SCHEMA = new URL('../../../../schemas/openapi/openapi.json', import.meta.url);
export const TARGET = new URL('../src/schema.d.ts', import.meta.url);
const HEADER =
  '// Generated by `npm run gen` (openapi-typescript) from schemas/openapi/openapi.json.\n' +
  '// Do not edit: change the platform, regenerate the document, then run `npm run gen` in web/.\n\n';

/** The types for `document` (the committed one unless given), as src/schema.d.ts holds them. */
export async function generate(document = SCHEMA) {
  return HEADER + astToString(await openapiTS(document));
}
