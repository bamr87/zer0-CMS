#!/usr/bin/env python3
"""Validate ABC board books against their canonical spec sidecar.

ABC books are GENERATED by the zer0-CMS ABC wizard, which writes two files into
this repo:

  pages/_books/<slug>/index.md   the board book (layout: book-abc)
  _data/abc_books/<slug>.json    the ABC Book Spec (the canonical content)

The spec sidecar is the source of truth (like the Dodge-and-Reena-Book content
repo is for the story books). This tool checks that the committed page still
matches its spec — the same drift guard `import_dodge_and_reena.py --check`
provides for the story books — so a hand-edit to a generated page fails CI.

It compares MEANING, not bytes: every A–Z letter's word, tagline, image, prompt,
plus the book's series / art_style / cover, must agree between page and spec.

Usage:
  python3 tools/import_abc_book.py            # validate every ABC book
  python3 tools/import_abc_book.py --check    # same, explicit (CI)
  python3 tools/import_abc_book.py --book it-alphabet
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    raise SystemExit("PyYAML is required: python3 -m pip install pyyaml")

REPO = Path(__file__).resolve().parent.parent
BOOKS_DIR = REPO / "pages" / "_books"
SPEC_DIR = REPO / "_data" / "abc_books"

# Book-level front-matter fields that must equal the spec.
BOOK_FIELDS = ("series", "art_style", "art_style_prompt", "palette")
# Per-letter fields that must equal the spec's alphabet entry. `alt` is
# canonical (the exporter writes it to both page and spec, and the theme renders
# it as the plate's alt / placeholder aria-label), so drift in it must be caught.
LETTER_FIELDS = ("word", "tagline", "image", "alt", "prompt")


def front_matter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    return yaml.safe_load(text[3:end]) or {}


def abc_books() -> list[Path]:
    """ABC book index pages (layout: book-abc)."""
    if not BOOKS_DIR.is_dir():
        return []
    pages = []
    for page in sorted(BOOKS_DIR.rglob("index.md")):
        fm = front_matter(page)
        if fm.get("layout") == "book-abc":
            pages.append(page)
    return pages


def check_book(page: Path) -> list[str]:
    """Return a list of drift messages for one book (empty == consistent)."""
    fm = front_matter(page)
    slug = fm.get("book")
    errors: list[str] = []

    if not slug:
        return [f"{page}: missing `book:` slug"]

    spec_path = SPEC_DIR / f"{slug}.json"
    if not spec_path.is_file():
        return [f"{slug}: no spec sidecar at {spec_path.relative_to(REPO)}"]

    spec = json.loads(spec_path.read_text(encoding="utf-8"))

    for field in BOOK_FIELDS:
        if fm.get(field) != spec.get(field):
            errors.append(f"{slug}: {field} drift (page != spec)")

    cover = spec.get("cover") or {}
    if fm.get("cover_image") != cover.get("image"):
        errors.append(f"{slug}: cover_image drift")
    if fm.get("cover_prompt") != cover.get("prompt"):
        errors.append(f"{slug}: cover_prompt drift")

    page_alphabet = fm.get("alphabet") or []
    page_letters = {e.get("letter"): e for e in page_alphabet}
    spec_letters = {e.get("letter"): e for e in spec.get("alphabet") or []}

    # A dict keyed by letter silently collapses duplicate `letter:` blocks
    # (keeping the last), which would let a duplicated-and-altered block pass the
    # field comparison below. Catch duplicates before they are collapsed.
    page_letter_seq = [e.get("letter") for e in page_alphabet]
    dupes = sorted({l for l in page_letter_seq if page_letter_seq.count(l) > 1})
    if dupes:
        errors.append(f"{slug}: page has duplicate letters {dupes}")

    missing = sorted(set(spec_letters) - set(page_letters))
    extra = sorted(set(page_letters) - set(spec_letters))
    if missing:
        errors.append(f"{slug}: page missing letters {missing}")
    if extra:
        errors.append(f"{slug}: page has unknown letters {extra}")

    for letter in sorted(set(page_letters) & set(spec_letters)):
        pe, se = page_letters[letter], spec_letters[letter]
        for field in LETTER_FIELDS:
            if pe.get(field) != se.get(field):
                errors.append(f"{slug}: letter {letter} {field} drift")

    return errors


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--book", help="only this book slug")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero on drift (default behaviour; kept for CI clarity)")
    args = ap.parse_args()

    pages = abc_books()
    if args.book:
        pages = [p for p in pages if front_matter(p).get("book") == args.book]

    if not pages:
        target = f" for --book {args.book}" if args.book else ""
        print(f"no ABC books found{target}")
        return 0

    all_errors: list[str] = []
    for page in pages:
        errors = check_book(page)
        slug = front_matter(page).get("book", page.name)
        if errors:
            all_errors.extend(errors)
            print(f"✗ {slug}: {len(errors)} issue(s)")
            for e in errors:
                print(f"    {e}")
        else:
            fm = front_matter(page)
            n = len(fm.get("alphabet") or [])
            print(f"✓ {slug}: {n} letters consistent with its spec")

    if all_errors:
        print(f"\n{len(all_errors)} drift issue(s) — regenerate with the zer0-CMS "
              f"ABC wizard, don't hand-edit generated pages.", file=sys.stderr)
        return 1
    print(f"\nAll {len(pages)} ABC book(s) match their spec.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
