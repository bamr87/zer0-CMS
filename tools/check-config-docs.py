#!/usr/bin/env python3
"""Generate and gate the documentation that is derived from source.

zer0-CMS documents its VS Code settings in two places: `docs/CONFIG.md`
section 5 is the full reference, and `README.md` names the handful that matter
on day one. The full reference used to be a hand-copied table, held to the
manifest by this script; a hand-copied table still drifted in its prose (it
called one setting the only `resource`-scoped one, when most are) even while
every id stayed right. So the table is now *generated*: section 5 carries an
``<!-- AUTO:settings:start -->`` … ``<!-- AUTO:settings:end -->`` span
rebuilt from `contributes.configuration`, and the hand-written prose around it
only explains. This is the fleet documentation framework's UPS-DOC-05
(bamr87/bamr87 specs/DOCS.md).

  python3 tools/check-config-docs.py           # check (what CI runs)
  python3 tools/check-config-docs.py --check   # the same, spelled out
  python3 tools/check-config-docs.py --write   # rewrite the generated spans in place

Because this is the documentation gate CI already calls, it also runs the
vendored docs index (`tools/docs_index.py --check`, or `--write`) over every
index file in `INDEXES`, so the tables in `docs/README.md` and `src/README.md`
cannot go stale behind a green build either.

The check fails when:

  * the span in `docs/CONFIG.md` is missing or differs from a fresh render —
    run `--write` and commit the result;
  * a backticked ``zer0Cms.*`` id anywhere in `docs/CONFIG.md` is not a
    setting the manifest contributes;
  * a backticked ``zer0Cms.*`` id in `README.md` is not one either;
  * a generated docs index (`docs/README.md`, `src/README.md`) no longer
    matches the documents' own summary lines.

`contributes.configuration` is read in both of the shapes VS Code accepts — a
single object with `properties`, or an array of titled sections each with their
own `properties` — and each titled section becomes one `###` subsection of the
span, in the manifest's order.

Exits 0 when everything agrees, 1 with a readable list of what is wrong, and 2
when a file it needs is unreadable or malformed. Standard library only, so it
runs anywhere `python3` does; CI runs it in `.github/workflows/extension.yml`.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent.parent

PACKAGE_JSON = ROOT / "package.json"
CONFIG_DOC = ROOT / "docs" / "CONFIG.md"
README = ROOT / "README.md"
DOCS_INDEX = ROOT / "tools" / "docs_index.py"
# Every file carrying an `<!-- AUTO:docs-index:start -->` span.
INDEXES = ("docs/README.md", "src/README.md")

START = "<!-- AUTO:settings:start -->"
END = "<!-- AUTO:settings:end -->"
NOTE = (
    "<!-- GENERATED by `python3 tools/check-config-docs.py --write` from "
    "package.json `contributes.configuration` — do not edit by hand -->"
)

# A setting is cited as an inline code span. Trailing dots are part of the id
# (`zer0Cms.panel.sections`), so the class deliberately includes `.`.
SETTING_REF = re.compile(r"`(zer0Cms\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*)`")

# VS Code's setting-link syntax inside a markdownDescription: `#zer0Cms.x.y#`.
SETTING_LINK = re.compile(r"`?#(zer0Cms\.[A-Za-z0-9_.]+)#`?")


def fail(message: str) -> NoReturn:
    """Report a problem the script cannot work around, and stop."""
    print(f"check-config-docs: {message}", file=sys.stderr)
    raise SystemExit(2)


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        fail(f"cannot read {path.relative_to(ROOT)}: {error}")


def load_manifest() -> tuple[list[dict], set[str]]:
    """Return (titled configuration sections, contributed command ids).

    Commands are collected only so an id documented in the wrong place gets a
    useful message instead of a bare "unknown".
    """
    try:
        manifest = json.loads(read_text(PACKAGE_JSON))
    except json.JSONDecodeError as error:
        fail(f"package.json is not valid JSON: {error}")

    contributes = manifest.get("contributes") or {}
    configuration = contributes.get("configuration")

    # Both shapes VS Code accepts: one object, or an array of titled sections.
    if isinstance(configuration, dict):
        sections = [configuration]
    elif isinstance(configuration, list):
        sections = [s for s in configuration if isinstance(s, dict)]
    elif configuration is None:
        sections = []
    else:
        fail("contributes.configuration is neither an object nor an array")

    sections = [s for s in sections if isinstance(s.get("properties"), dict)]
    commands = {
        c["command"]
        for c in contributes.get("commands") or []
        if isinstance(c, dict) and isinstance(c.get("command"), str)
    }
    return sections, commands


# --- rendering ----------------------------------------------------------------


def literal(value: object) -> str:
    """A default as the JSON a person would type into settings.json."""
    return "`" + json.dumps(value, ensure_ascii=False) + "`"


def type_of(spec: dict) -> str:
    kind = spec.get("type", "")
    if isinstance(kind, list):
        kind = " \\| ".join(str(k) for k in kind)
    if kind == "array" and isinstance(spec.get("items"), dict) and spec["items"].get("type"):
        return f"{spec['items']['type']}[]"
    return str(kind)


def describe(spec: dict) -> str:
    """The manifest's own description, plus the constraints VS Code enforces."""
    text = spec.get("markdownDescription") or spec.get("description") or ""
    text = SETTING_LINK.sub(lambda m: f"`{m.group(1)}`", text)
    text = re.sub(r"\s+", " ", text).strip()
    extra = []
    enum = spec.get("enum")
    items = spec.get("items") if isinstance(spec.get("items"), dict) else {}
    if isinstance(enum, list):
        extra.append("One of: " + ", ".join(f"`{v}`" for v in enum) + ".")
    elif isinstance(items.get("enum"), list):
        extra.append("Allowed values: " + ", ".join(f"`{v}`" for v in items["enum"]) + ".")
    low, high = spec.get("minimum"), spec.get("maximum")
    if low is not None and high is not None:
        extra.append(f"Range {low}–{high}.")
    elif low is not None:
        extra.append(f"Minimum {low}.")
    elif high is not None:
        extra.append(f"Maximum {high}.")
    out = " ".join(p for p in [text, *extra] if p)
    return out.replace("|", "\\|")


def render(sections: list[dict]) -> str:
    total = sum(len(s["properties"]) for s in sections)
    lines = [
        START,
        NOTE,
        "",
        f"{total} settings in {len(sections)} sections, in the manifest's order.",
    ]
    for index, section in enumerate(sections, 1):
        title = section.get("title") or f"Section {index}"
        lines += [
            "",
            f"### {title}",
            "",
            "| Setting | Type | Default | Scope | What it does |",
            "|---|---|---|---|---|",
        ]
        for key, spec in section["properties"].items():
            if not isinstance(spec, dict):
                fail(f"contributes.configuration property {key} is not an object")
            default = literal(spec["default"]) if "default" in spec else "—"
            scope = spec.get("scope", "window")
            lines.append(f"| `{key}` | {type_of(spec)} | {default} | {scope} | {describe(spec)} |")
    lines += ["", END]
    return "\n".join(lines)


def splice(text: str, span: str) -> str | None:
    """Return `text` with its span replaced by `span`, or None when it has none."""
    start = text.find(START)
    end = text.find(END, start + 1) if start >= 0 else -1
    if start < 0 or end < 0:
        return None
    return text[:start] + span + text[end + len(END) :]


# --- the docs index -------------------------------------------------------------


def docs_index(write: bool) -> list[str]:
    """Run the vendored index generator over every index; return the stale ones."""
    if not DOCS_INDEX.is_file():
        fail("tools/docs_index.py is missing — vendor it from the bamr87 hub")
    mode = "--write" if write else "--check"
    stale = []
    for index in INDEXES:
        result = subprocess.run(
            [sys.executable, str(DOCS_INDEX), mode, "--root", str(ROOT), "--index", index],
            capture_output=True,
            text=True,
            check=False,
        )
        for stream in (result.stdout, result.stderr):
            if stream.strip():
                print(stream.rstrip(), file=sys.stderr if result.returncode else sys.stdout)
        if result.returncode:
            stale.append(index)
    return stale


# --- checking -----------------------------------------------------------------


def cited(text: str) -> set[str]:
    return set(SETTING_REF.findall(text))


def report(title: str, ids: set[str], note: str) -> None:
    print(f"\n{title}", file=sys.stderr)
    for setting in sorted(ids):
        print(f"  - {setting}", file=sys.stderr)
    print(f"  {note}", file=sys.stderr)


def ghost_note(ids: set[str], commands: set[str]) -> str:
    overlap = sorted(ids & commands)
    if overlap:
        return (
            "These are contributed COMMANDS, not settings: "
            + ", ".join(overlap)
            + ". Cite them outside the settings prose."
        )
    return "Fix the reference, or restore the setting in package.json."


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify only (the default)")
    mode.add_argument("--write", action="store_true", help="rewrite the generated span in docs/CONFIG.md")
    args = parser.parse_args(argv)

    sections, commands = load_manifest()
    settings = {key for s in sections for key in s["properties"]}
    if not settings:
        fail("package.json contributes no configuration properties")

    current = read_text(CONFIG_DOC)
    fresh = splice(current, render(sections))
    if fresh is None:
        fail(f"docs/CONFIG.md has no {START} … {END} span — add the two marker lines to section 5")

    if args.write:
        if fresh != current:
            CONFIG_DOC.write_text(fresh, encoding="utf-8")
            print(f"check-config-docs: wrote docs/CONFIG.md ({len(settings)} settings)")
        else:
            print("check-config-docs: docs/CONFIG.md already current")
        current = fresh

    stale = fresh != current
    doc_ghosts = cited(current) - settings
    readme_cited = cited(read_text(README))
    readme_ghosts = readme_cited - settings
    stale_indexes = docs_index(args.write)

    if not (stale or doc_ghosts or readme_ghosts or stale_indexes):
        if not args.write:
            print(
                f"check-config-docs: OK — {len(settings)} settings, generated span in "
                f"docs/CONFIG.md §5 is current; {len(readme_cited)} cited in README.md, all real; "
                f"docs index current in {', '.join(INDEXES)}."
            )
        return 0

    print(f"check-config-docs: FAILED — {len(settings)} contributed settings.", file=sys.stderr)
    if stale:
        print(
            "\nThe generated settings span in docs/CONFIG.md is stale.\n"
            "  Run `python3 tools/check-config-docs.py --write` and commit the result.",
            file=sys.stderr,
        )
    if doc_ghosts:
        report("Cited in docs/CONFIG.md but not contributed:", doc_ghosts, ghost_note(doc_ghosts, commands))
    if readme_ghosts:
        report("Cited in README.md but not contributed:", readme_ghosts, ghost_note(readme_ghosts, commands))
    if stale_indexes:
        print(
            f"\nThe docs index is stale or missing its span in: {', '.join(stale_indexes)}.\n"
            "  Run `python3 tools/check-config-docs.py --write` and commit the result.",
            file=sys.stderr,
        )
    return 1


if __name__ == "__main__":
    sys.exit(main())
