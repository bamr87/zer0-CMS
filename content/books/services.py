# ── finding books ──────────────────────────────────────────────────────────


def is_template(book) -> bool:
    """A template (`library/_template`) is a book whose directory starts with `_`; it is never on the shelf."""
    return files.book_dir(book).startswith("_")


def can_open(book, user) -> bool:
    perms = book.permissions_for_user(user)
    return perms.can_edit() or perms.can_publish()


def shelf(user, *, site=None, templates=False) -> list[BookPage]:
    """The books a person may open, in tree order (templates only when asked)."""
    pages = visible_pages(user).type(BookPage).order_by("path")
    if site is not None:
        pages = pages.descendant_of(site.root_page, inclusive=True)
    return [b for b in (p.specific for p in pages) if can_open(b, user) and is_template(b) == templates]


def find(user, pk) -> BookPage:
    """A book the person may open, else a 404."""
    page = visible_pages(user).type(BookPage).filter(pk=pk).first()
    if page is None or not can_open(page.specific, user):
        raise NotFound(f"no book {pk}")
    return page.specific


def library_root() -> SiteRootPage:
    root = SiteRootPage.objects.filter(site_key=settings.BOOKS_SITE_KEY).first()
    return root or files.ensure_library(settings.BOOKS_SITE_KEY)


def by_slug(slug: str, site_key: str | None = None) -> BookPage:
    for book in files.library_books(site_key or settings.BOOKS_SITE_KEY):
        if files.book_dir(book) == slug:
            return book.specific
    raise NotFound(f"no book {slug!r} in the {site_key or settings.BOOKS_SITE_KEY} library")


# ── reading a book ─────────────────────────────────────────────────────────


def read(book: BookPage) -> library.Book:
    """The book as its files say it — what validation, statistics and the AI read."""
    return library.Book.read(files.book_dir(book), files.book_tree(book))


def stats(rm: library.Book) -> dict:
    chapters = rm.chapters
    longest = max(chapters, key=lambda c: c.word_count, default=None)
    shortest = min(chapters, key=lambda c: c.word_count, default=None)

    def brief(c):
        return {"number": c.number, "title": c.title, "word_count": c.word_count} if c else None

    return {
        "chapters": len(chapters),
        "status_counts": rm.status_counts(),
        "word_count": rm.word_count,
        "target_word_count": rm.target_word_count,
        "planned_chapters": rm.planned_chapters,
        "average": rm.word_count // len(chapters) if chapters else 0,
        "longest": brief(longest),
        "shortest": brief(shortest),
        "progress": round(rm.progress, 4),
    }


def summary(book: BookPage, rm: library.Book | None = None) -> dict:
    """One row of the shelf."""
    from api.pages import status_of

    rm = rm or read(book)
    site = book.get_site()
    return {
        "id": book.pk,
        "slug": files.book_dir(book),
        "title": rm.title,
        "status": rm.status,
        "page_status": status_of(book),
        "profile": book.profile,
        "logline": rm.logline,
        "genre": rm.genre,
        "chapters": len(rm.chapters),
        "planned_chapters": rm.planned_chapters,
        "word_count": rm.word_count,
        "target_word_count": rm.target_word_count,
        "progress": round(rm.progress, 4),
        "site_id": site.pk if site else None,
        "template": is_template(book),
    }


def detail(book: BookPage, user) -> dict:
    """A book's overview: its shelf row, its chapters in order, statistics,
    findings counts, its other files, and what the person may do."""
    rm = read(book)
    pages = {c.number: c for c in files.book_chapters(book)}
    issues = library.validate(rm)
    perms = book.permissions_for_user(user)
    return {
        **summary(book, rm),
        "stats": stats(rm),
        "chapter_list": [
            {
                "id": pages[c.number].pk if c.number in pages else None,
                "number": c.number,
                "title": c.title,
                "subtitle": c.subtitle,
                "act": c.act,
                "status": c.status,
                "pov": c.pov,
                "word_count": c.word_count,
                "path": c.path,
                "errors": sum(1 for i in issues if i.path == c.path and i.level == library.ERROR),
                "warnings": sum(1 for i in issues if i.path == c.path and i.level == library.WARNING),
            }
            for c in rm.chapters
        ],
        "errors": sum(1 for i in issues if i.level == library.ERROR),
        "warnings": sum(1 for i in issues if i.level == library.WARNING),
        "documents": sorted(p for p in rm.tree if not library.is_chapter(p)),
        "can_edit": perms.can_edit(),
        "can_add_chapter": ChapterPage in creatable_types(book, user),
    }


def validate(book: BookPage) -> list[library.Issue]:
    return library.validate(read(book))


def manuscript(book: BookPage, *, include_outline=False) -> str:
    return library.manuscript(read(book), include_outline=include_outline)


def library_data(books) -> dict:
    """`library.json`: every book as data, as bookshelf wrote it."""
    prefix = Path(settings.BOOKS_LIBRARY_DIR).name
    data = [library.book_to_dict(read(book), prefix) for book in books]
    return {"books": data, "word_count": sum(b["word_count"] for b in data)}


def dashboard(books, *, generated: str) -> str:
    """The static shelf (`index.html`): totals, a card per book with its chapter table, and the findings."""
    rows = []
    for book in books:
        rm = read(book)
        issues = library.validate(rm)
        rows.append({"book": library.book_to_dict(rm), "stats": stats(rm), "issues": [i.as_dict() for i in issues]})
    context = {
        "books": rows,
        "generated": generated,
        "word_count": sum(r["book"]["word_count"] for r in rows),
        "chapters": sum(len(r["book"]["chapters"]) for r in rows),
        "errors": sum(1 for r in rows for i in r["issues"] if i["level"] == library.ERROR),
        "warnings": sum(1 for r in rows for i in r["issues"] if i["level"] == library.WARNING),
    }
    return render_to_string("books/dashboard.html", context)


# ── making books and chapters ──────────────────────────────────────────────


def _require(allowed: bool, message: str):
    if not allowed:
        raise PermissionDenied(message)


def template_for(parent) -> BookPage | None:
    """The template a new book under `parent` starts from: `_template` beside it, else the library's."""
    for root in (parent, library_root()):
        found = next((b for b in BookPage.objects.child_of(root).specific() if files.book_dir(b) == "_template"), None)
        if found is not None:
            return found
    return None


@transaction.atomic
def new_book(
    parent, user, *, title: str, slug: str = "", logline: str = "", genre: str = "", template=None, check=True
) -> BookPage:
    """A book from a template, as a draft: the template's manifest, outline
    (`{{title}}` and `{{slug}}` filled), notes and other files, stamped with
    its slug, title, `status: idea` and today's date — `books new`. `check`
    is off only for an operator's shell (manage.py books)."""
    _require(not check or BookPage in creatable_types(parent, user), f"{user} may not create a book here")
    if not title.strip():
        raise ValidationError({"title": ["a book needs a title"]})
    slug = slug or slugify(title)
    template = template or template_for(parent)
    book = BookPage(owner=user, live=False, has_unpublished_changes=True)
    if template is not None:
        source = template.get_latest_revision_as_object()
        for name in BookPage.manuscript_fields + ("subtitle", "author", "series", "profile", "documents"):
            setattr(book, name, getattr(source, name))
        book.outline = source.outline.replace("{{title}}", title).replace("{{slug}}", slug)
        book.front_matter = dict(source.front_matter or {})
    book.title, book.slug = title, slug
    book.book_status, book.logline, book.genre = "idea", logline or book.logline, genre or book.genre
    book.front_matter.update(slug=slug, title=title, status="idea", created=date.today().isoformat())
    for key, value in (("logline", logline), ("genre", genre)):
        if value:
            book.front_matter[key] = value
    parent.add_child(instance=book)
    save_draft(book, user, log_action="wagtail.create")
    return book


def act_for(book: BookPage, number: int) -> int:
    """Spread chapter numbers evenly across the book's acts."""
    count = ChapterPage.objects.child_of(book).count()
    planned = max(book.planned_chapters or count, number)
    acts = max(1, book.acts or 1)
    return min(acts, (number - 1) * acts // planned + 1)


def chapter_body(title: str, purpose: str = "") -> list[dict]:
    purpose = purpose or "What this chapter has to accomplish for the plot, the character and the themes."
    return to_blocks(CHAPTER_SKELETON.format(title=title, purpose=purpose))


@transaction.atomic
def add_chapter(
    book: BookPage, user, *, title: str, number=None, act=None, purpose: str = "", check=True
) -> ChapterPage:
    """The next chapter as a draft stub from the chapter skeleton, its act
    inferred from its number — `books add-chapter`."""
    _require(not check or ChapterPage in creatable_types(book, user), f"{user} may not add a chapter to this book")
    if not title.strip():
        raise ValidationError({"title": ["a chapter needs a title"]})
    latest = book.get_latest_revision_as_object()
    numbers = [c.number for c in files.book_chapters(book) if c.number]
    number = number or (max(numbers) + 1 if numbers else 1)
    if number in numbers:
        raise ValidationError({"number": [f"chapter {number} already exists in this book"]})
    chapter = ChapterPage(
        owner=user,
        live=False,
        has_unpublished_changes=True,
        title=title,
        slug=_unique_slug(book, library.chapter_filename(number)[:-3]),
        number=number,
        act=act or act_for(latest, number),
        chapter_status="stub",
        pov=latest.pov or "Third person limited",
        era=latest.era,
        body=chapter_body(title, purpose),
    )
    book.add_child(instance=chapter)
    save_draft(chapter, user, log_action="wagtail.create")
    return chapter


# ── the AI tasks ───────────────────────────────────────────────────────────


def agent() -> AgentDefinition:
    definition = AgentDefinition.objects.filter(slug=AGENT).first()
    if definition is None:
        raise Unavailable(f"the {AGENT} agent is not synced: run manage.py sync_agents --publish")
    return definition


def bundled(key: str) -> Assistant:
    """A bundled book assistant (books/data/bundled.yaml)."""
    row = Assistant.objects.filter(public_id=stable_id("bundled-assistant", key)).first()
    if row is None:
        raise Unavailable(f"the bundled assistant {key!r} is missing: run manage.py migrate")
    return row


def assistant_for(task: Task, user, chosen=None) -> Assistant:
    assistant = chosen or bundled(task.assistant)
    if not usable(assistant, user):
        raise Forbidden(f"assistant {assistant.public_id} is not one {user} may use")
    return assistant


def run_task(book: BookPage, user, *, task: str, chapter=None, instruction="", selection="", assistant=None):
    """Queue a book task as a run of the `books` agent on the chapter (or the
    book): the worker assembles the book's context, asks the assistant, and —
    for draft, continue and revise — proposes the result as suggestions."""
    found = TASKS.get(task)
    if found is None:
        raise Invalid(f"no task {task!r}; one of {', '.join(TASKS)}")
    if found.chapter and chapter is None:
        raise Invalid(f"{found.label} works on a chapter: choose one")
    if task == "revise" and not selection.strip():
        raise Invalid("revise needs the passage to rewrite")
    if chapter is not None and chapter.get_parent().pk != book.pk:
        raise Invalid(f"chapter {chapter.pk} is not in this book")
    target = chapter or book
    if not target.permissions_for_user(user).can_edit():
        raise Forbidden(f"{user} may not edit page {target.pk}")
    chosen = assistant_for(found, user, assistant)
    provider_slug(chosen)
    data = {"task": task, "assistant": str(chosen.public_id), "instruction": instruction, "selection": selection}
    try:
        return start_run(agent(), trigger="rest", target=target, input=data, user=user)
    except RunRefused as e:
        raise Conflict(str(e)) from e


def outline_from_premise(user, *, premise: str, parent=None, assistant=None) -> tuple[Brief, AgentRun]:
    """A brief that the bundled outliner turns into a structured outline —
    synopsis, themes, the three acts' beats, the arc, the cast, the chapter
    plan — as a run; `create_from_brief` makes the book from it."""
    if not premise.strip():
        raise Invalid("a book starts from a premise")
    outliner = assistant_for(TASKS["outline"], user, assistant)
    brief = Brief.objects.create(
        owner=user,
        title=premise.strip()[:120],
        prompt=premise.strip(),
        assistant=outliner,
        output_schema=outliner.output_schema,
        page_type="cms.BookPage",
        parent=parent or library_root(),
    )
    return brief, generate_brief(brief, user=user)


def outline_schema() -> dict:
    return OutputSchema.objects.get(public_id=stable_id("bundled-schema", OUTLINE_SCHEMA_KEY)).schema


@transaction.atomic
def create_from_brief(brief: Brief, user, *, parent=None) -> BookPage:
    """The person accepts an outline: a draft book with its facts, the
    outline, and a stub per planned chapter, under `parent` (else the brief's).
    Nothing is published."""
    brief = Brief.objects.select_for_update().get(pk=brief.pk)
    if not brief.can_edit(user):
        raise Forbidden(f"brief {brief.public_id} is not {user}'s to use")
    if brief.status != Brief.READY:
        raise Conflict(f"a book is made from a ready outline; this one is {brief.status}")
    data = brief.result if isinstance(brief.result, dict) else None
    if data is None or first_error(outline_schema(), data):
        raise Invalid("the brief's result is not a book outline")
    parent = (parent or brief.parent or library_root()).specific
    _require(BookPage in creatable_types(parent, user), f"{user} may not create a book here")
    title = (data["title"] or brief.metadata.get("title") or brief.title).strip()[:255]
    book = BookPage(
        owner=user,
        live=False,
        has_unpublished_changes=True,
        title=title,
        slug=_unique_slug(parent, slugify(title)[:200] or "book"),
        book_status="outlining",
        logline=data["logline"],
        genre=data["genre"],
        pov=data["pov"],
        tense=data["tense"],
        era=data["era"],
        protagonist=data["protagonist"],
        acts=len(data["acts"]) or 3,
        planned_chapters=len(data["chapters"]) or None,
        themes=[t["name"] for t in data["themes"] if t["name"].strip()],
        cast=[name for name in data["cast"] if name.strip()],
        outline=brief.markdown,
    )
    book.front_matter = {"slug": book.slug, "title": title, "created": date.today().isoformat()}
    parent.add_child(instance=book)
    save_draft(book, user, log_action="wagtail.create")
    for number, plan in enumerate(sorted(data["chapters"], key=lambda c: c["number"]), start=1):
        act = min(max(plan["act"], 1), book.acts)
        add_chapter(book, user, title=plan["title"], number=number, act=act, purpose=plan["beat"])
    Brief.objects.filter(pk=brief.pk).update(
        page=book, status=Brief.APPLIED, applied_at=timezone.now(), updated_at=timezone.now()
    )
    return book


# ── memory and the bundled AI setup ────────────────────────────────────────


def remember(book: BookPage) -> None:
    """The continuity ledger and the character bible of `book` (a revision's
    content) as the agents' memory of it — scope `page`, the book's id, keys
    `book.continuity` and `book.characters`: `memory.recall` reads them."""
    for key, text in (("book.continuity", book.continuity_notes), ("book.characters", book.character_notes)):
        if text.strip():
            Memory.objects.update_or_create(
                scope="page",
                scope_id=str(book.pk),
                key=key,
                defaults={"value": {"book": files.book_dir(book), "title": book.title, "text": text}},
            )
        else:
            Memory.objects.filter(scope="page", scope_id=str(book.pk), key=key).delete()


def import_bundled(state=apps) -> dict:
    """Create the bundled book schemas, assistants and pipeline that do not
    exist yet (each public id derived from its key); a row a person edited is
    left as it is. `state` is the model registry — after a migrate, the migrated one."""
    spec = yaml.safe_load((DATA / "bundled.yaml").read_text(encoding="utf-8"))
    rules = (DATA / "house-rules.md").read_text(encoding="utf-8")
    schemas, assistants, pipelines = {}, {}, []
    rows = {name: state.get_model("ai", name).objects for name in ("OutputSchema", "Assistant", "Pipeline")}
    for item in spec["schemas"]:
        schemas[item["key"]], _ = rows["OutputSchema"].get_or_create(
            public_id=stable_id("bundled-schema", item["key"]),
            defaults={
                "name": item["name"],
                "description": item["description"],
                "schema": json.loads((DATA / item["file"]).read_text(encoding="utf-8")),
                "render_template": item["template"],
                "bundled": True,
                "visibility": "shared",
            },
        )
    for item in spec["assistants"]:
        assistants[item["key"]], _ = rows["Assistant"].get_or_create(
            public_id=stable_id("bundled-assistant", item["key"]),
            defaults={
                "name": item["name"],
                "description": item["description"],
                "instructions": f"{rules}\n{item['role']}".strip(),
                "output_schema": schemas.get(item.get("output_schema")),
                "visibility": "shared",
            },
        )
    for item in spec["pipelines"]:
        pipeline, created = rows["Pipeline"].get_or_create(
            public_id=stable_id("bundled-pipeline", item["key"]),
            defaults={"name": item["name"], "description": item["description"], "visibility": "shared"},
        )
        if created:
            for position, step in enumerate(item["steps"], start=1):
                pipeline.steps.create(position=position, assistant=assistants[step["assistant"]], source=step["source"])
        pipelines.append(pipeline)
    return {"schemas": list(schemas.values()), "assistants": list(assistants.values()), "pipelines": pipelines}
