"""What the books app does — the shelf, a book's facts and chapters, new books
and chapters, validation, statistics, the manuscript, the library's data and
dashboard, and the AI tasks — so the API, the `manage.py books` commands and the
agent's handler stay thin (TARGET.md § Rules that keep models and views
manageable). The bookshelf CLI's commands map one to one: `list`, `show`, `new`,
`add-chapter`, `validate`, `stats`, `build`, `dashboard`, `context`.

Everything a book reports is computed from its rendered file set
(`files.book_tree`, read by `library.Book`), the text `export_books` writes:
what the studio shows is what `library/<slug>/` says. Every write is a draft
revision checked against the person's Wagtail page permissions; nothing here
publishes. Every AI task is a run of the GitOps `books` agent
(agents/definitions/books.yaml), queued on Celery and reviewed as suggestions;
a book made from a premise is an `ai.Brief` generated by the bundled outliner
and turned into a draft book and its chapter stubs only when a person asks.
"""

